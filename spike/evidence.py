def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    create = commands.add_parser("template", help="write a completely pending evidence template")
    create.add_argument("output", type=Path)
    report = commands.add_parser("summarize", help="summarize recorded evidence; never supplies measurements")
    report.add_argument("input", type=Path)
    report.add_argument("--output", type=Path)
    args = parser.parse_args()
    if args.command == "template":
        if args.output.exists():
            parser.error("output already exists; choose a fresh file to preserve recorded evidence")
        args.output.write_text(json.dumps(template(), indent=2) + "\n", encoding="utf-8")
        print(f"Created {len(expected_rows())} pending trials: {args.output}")
    else:
        document = json.loads(args.input.read_text(encoding="utf-8"))
        rendered = json.dumps(summarize(document), indent=2) + "\n"
        if args.output:
            if args.output.exists():
                parser.error("summary output already exists; choose a fresh file to preserve earlier reports")
            args.output.write_text(rendered, encoding="utf-8")
        else:
            print(rendered, end="")


if __name__ == "__main__":
    main()
